"""Build src/core/grapheme-data.ts.

    uv run scripts/grapheme-data.py

Every code point UAX #29 has classed as Prepend in any Unicode from FLOOR, the
version the oldest supported Node's ICU segments at, through the version
scripts/cell-widths.py pins. The engine's segmenter still forms each cluster, so
a code point Prepend at any of those versions may be joined to its base on some
Node and by some terminal; the library cuts every one of them, on every Node,
and seals the cut on the wire. Cutting one an engine never joined costs nothing:
Rich counts the two apart already.
"""

import re
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
UNICODE = re.search(r'^UNICODE = "([0-9.]+)"$', (HERE / "cell-widths.py").read_text(), re.M).group(1)
# Node 20.0 ships ICU 73, which segments at Unicode 15.0.
FLOOR = "15.0.0"
VERSIONS = ["15.0.0", "15.1.0", "16.0.0", "17.0.0"]
if VERSIONS[0] != FLOOR or VERSIONS[-1] != UNICODE:
    raise SystemExit(f"VERSIONS must run from {FLOOR} to the pinned {UNICODE}")
OUT = HERE.parent / "src/core/grapheme-data.ts"
WIDTH = 120

HEADER = f"""\
/**
 * Every code point UAX #29 has classed as Grapheme_Cluster_Break=Prepend in
 * Unicode {FLOOR} through {UNICODE}, which any supported Node's segmenter may
 * join to what follows. Generated by scripts/grapheme-data.py; regenerate
 * rather than edit.
 */

const PREPEND: ReadonlySet<number> = new Set([
"""

FOOTER = """\
]);

/** Whether `codePoint` is a Prepend at some Unicode a supported Node segments at. */
export function isPrependCodePoint(codePoint: number): boolean {
  return PREPEND.has(codePoint);
}
"""


def main() -> None:
    points: set[int] = set()
    for version in VERSIONS:
        url = f"https://www.unicode.org/Public/{version}/ucd/auxiliary/GraphemeBreakProperty.txt"
        with urllib.request.urlopen(url) as response:
            lines = response.read().decode("utf-8").splitlines()
        for line in lines:
            row = [field.strip() for field in line.split("#")[0].split(";")]
            if len(row) != 2 or row[1] != "Prepend":
                continue
            first, _, last = row[0].partition("..")
            points.update(range(int(first, 16), int(last or first, 16) + 1))

    out, line = [], "  "
    for a in sorted(points):
        entry = f"0x{a:x},"
        if len(line) + len(entry) + 1 > WIDTH:
            out.append(line.rstrip())
            line = "  "
        line += entry + " "
    out.append(line.rstrip())
    OUT.write_text(HEADER + "\n".join(out) + "\n" + FOOTER)
    print(f"{OUT}: {len(points)} Prepend code points")


if __name__ == "__main__":
    main()
