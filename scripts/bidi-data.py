"""Build src/core/bidi-data.ts.

    uv run scripts/bidi-data.py

The tables UAX #9 and Arabic joining read, from the Unicode Character Database
at the version scripts/cell-widths.py pins, so a width and a direction answer
from one Unicode. Moving to a newer one is a change to both constants and a
re-run of both scripts.
"""

import re
import urllib.request
from pathlib import Path

UNICODE = "17.0.0"
OUT = Path(__file__).resolve().parent.parent / "src/core/bidi-data.ts"
WIDTH = 120
BASE = f"https://www.unicode.org/Public/{UNICODE}/ucd"

# Every class but L, which is what a code point in no range is.
CLASSES = ["R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
           "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]
# Every joining type but U, likewise: non-joining.
JOINING = ["R", "L", "D", "C", "T"]
FORMS = ["isolated", "final", "initial", "medial"]

HEADER = f"""\
/**
 * The Unicode properties UAX #9 and Arabic joining read. Generated by
 * scripts/bidi-data.py from the Unicode {UNICODE} Character Database; regenerate
 * rather than edit.
 */

/** The bidi classes other than L, in the order `CLASS_RANGES` numbers them. */
export const BIDI_CLASSES = {CLASSES!r} as const;

/** The joining types other than U, in the order `JOINING_RANGES` numbers them. */
export const JOINING_TYPES = {JOINING!r} as const;

"""


def fetch(path: str) -> list[str]:
    with urllib.request.urlopen(f"{BASE}/{path}") as response:
        return response.read().decode("utf-8").splitlines()


def fields(line: str) -> list[str]:
    return [field.strip() for field in line.split("#")[0].split(";")]


def span(text: str) -> tuple[int, int]:
    first, _, last = text.partition("..")
    return int(first, 16), int(last or first, 16)


def merged(entries: list[tuple[int, int, int]]) -> list[list[int]]:
    out: list[list[int]] = []
    for first, last, value in sorted(entries):
        if out and out[-1][1] >= first:
            raise SystemExit(f"{first:#x} overlaps the range before it")
        if out and out[-1][1] + 1 == first and out[-1][2] == value:
            out[-1][1] = last
        else:
            out.append([first, last, value])
    return out


def bidi_classes() -> list[list[int]]:
    """Each code point's class, the file's `@missing` block defaults under its own rows."""
    lines = fetch("extracted/DerivedBidiClass.txt")
    classes: dict[int, str] = {}
    for line in lines:
        missing = re.match(r"# @missing: (\S+)\s*;\s*(\S+)", line)
        if missing is None:
            continue
        name = re.sub(r"[^A-Za-z]", "", missing[2])
        short = {"RightToLeft": "R", "ArabicLetter": "AL", "EuropeanTerminator": "ET",
                 "BoundaryNeutral": "BN", "LeftToRight": "L"}.get(name, name)
        first, last = span(missing[1])
        classes.update(dict.fromkeys(range(first, last + 1), short))
    for line in lines:
        row = fields(line)
        if len(row) == 2 and row[0]:
            first, last = span(row[0])
            classes.update(dict.fromkeys(range(first, last + 1), row[1]))
    return merged([(cp, cp, CLASSES.index(name)) for cp, name in classes.items() if name != "L"])


def joining_types() -> list[list[int]]:
    entries = []
    for line in fetch("extracted/DerivedJoiningType.txt"):
        row = fields(line)
        if len(row) == 2 and row[0] and row[1] != "U":
            first, last = span(row[0])
            entries.append((first, last, JOINING.index(row[1])))
    return merged(entries)


def brackets() -> list[tuple[int, int]]:
    pairs = []
    for line in fetch("BidiBrackets.txt"):
        row = fields(line)
        if len(row) == 3 and row[2] == "o":
            pairs.append((int(row[0], 16), int(row[1], 16)))
    return sorted(pairs)


def mirrors() -> list[tuple[int, int]]:
    pairs = []
    for line in fetch("BidiMirroring.txt"):
        row = fields(line)
        if len(row) == 2 and row[0]:
            pairs.append((int(row[0], 16), int(row[1], 16)))
    return sorted(pairs)


def presentation_forms() -> list[tuple[int, ...]]:
    """[letter, isolated, final, initial, medial], 0 where Unicode encodes no such form."""
    forms: dict[int, list[int]] = {}
    for line in fetch("UnicodeData.txt"):
        row = line.split(";")
        tag = re.fullmatch(r"<(\w+)> ([0-9A-F]+)", row[5])
        if tag is not None and tag[1] in FORMS:
            letters = forms.setdefault(int(tag[2], 16), [0, 0, 0, 0])
            # The first encoded form stands: a letter's later ones are its compatibility duplicates.
            slot = FORMS.index(tag[1])
            letters[slot] = letters[slot] or int(row[0], 16)
    return [(letter, *found) for letter, found in sorted(forms.items())]


def pack(entries: list[str]) -> str:
    lines, line = [], "  "
    for entry in entries:
        if len(line) + len(entry) + 1 > WIDTH:
            lines.append(line.rstrip())
            line = "  "
        line += entry + " "
    lines.append(line.rstrip())
    return "\n".join(lines)


def table(comment: str, name: str, kind: str, rows: list[str]) -> str:
    return f"// {comment}\nexport const {name}: {kind} = [\n{pack(rows)}\n];\n"


def hex_row(row) -> str:
    return "[" + ", ".join(f"0x{value:x}" if value else "0" for value in row) + "],"


def range_row(row: list[int]) -> str:
    return f"[0x{row[0]:x}, 0x{row[1]:x}, {row[2]}],"


def main() -> None:
    classes, joining, pairs, mirrored, forms = bidi_classes(), joining_types(), brackets(), mirrors(), presentation_forms()
    OUT.write_text(HEADER + "\n".join([
        table("Every range of code points not L, as [first, last, index into BIDI_CLASSES]: ascending, disjoint.",
              "CLASS_RANGES", "readonly (readonly [number, number, number])[]", [range_row(r) for r in classes]),
        table("Every range of code points not U, as [first, last, index into JOINING_TYPES]: ascending, disjoint.",
              "JOINING_RANGES", "readonly (readonly [number, number, number])[]", [range_row(r) for r in joining]),
        table("Every paired bracket as [opening, closing].",
              "BRACKET_PAIRS", "readonly (readonly [number, number])[]", [hex_row(p) for p in pairs]),
        table("Every Bidi_Mirroring_Glyph as [code point, its mirror].",
              "MIRRORS", "readonly (readonly [number, number])[]", [hex_row(p) for p in mirrored]),
        table("Every letter with a presentation form, as [letter, isolated, final, initial, medial]; 0 is none encoded.",
              "PRESENTATION_FORMS", "readonly (readonly [number, number, number, number, number])[]", [hex_row(f) for f in forms]),
    ]))
    print(f"{OUT}: {len(classes)} class ranges, {len(joining)} joining ranges, {len(pairs)} bracket pairs, "
          f"{len(mirrored)} mirrors, {len(forms)} letters with forms")


if __name__ == "__main__":
    main()
