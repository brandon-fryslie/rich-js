"""Build src/core/cell-widths.ts.

    uv run scripts/cell-widths.py

The table is the one Rich's cell_len measures with: rich._unicode_data for
Unicode 17.0.0, the latest Rich 15.0.0 carries and the one it picks when
UNICODE_VERSION is unset. Rich generates it from the wcwidth project's data.
Pinning both versions here is what makes the output reproducible; moving to a
newer Rich or Unicode is a change to the two constants below and a re-run.
"""

from importlib.metadata import version
from pathlib import Path

from rich._unicode_data import load

RICH = "15.0.0"
UNICODE = "17.0.0"
OUT = Path(__file__).resolve().parent.parent / "src/core/cell-widths.ts"
WIDTH = 120

HEADER = f"""\
/**
 * The cells Rich's `cell_len` gives each code point, and the code points VS16
 * widens. Generated by scripts/cell-widths.py from Rich {RICH}'s Unicode {UNICODE}
 * table, which Rich builds from wcwidth's data; regenerate rather than edit.
 */

// Every range of code points that does not take one cell, as [first, last,
// cells]: ascending, disjoint, adjacent ranges of one width merged.
const RANGES: readonly (readonly [number, number, 0 | 2])[] = [
"""

MIDDLE = """\
];

// The code points one cell wide on their own and two when VARIATION SELECTOR-16
// asks for emoji presentation.
const NARROW_TO_WIDE: ReadonlySet<number> = new Set([
"""

FOOTER = """\
]);

/** The cells Rich gives `codePoint` on its own: none for a C0 or C1 control. */
export function codePointWidth(codePoint: number): 0 | 1 | 2 {
  if (codePoint < 0x20 || (codePoint >= 0x7f && codePoint < 0xa0)) return 0;
  let low = 0;
  let high = RANGES.length - 1;
  while (low <= high) {
    const mid = (low + high) >> 1;
    const [first, last, cells] = RANGES[mid]!;
    if (codePoint < first) high = mid - 1;
    else if (codePoint > last) low = mid + 1;
    else return cells;
  }
  return 1;
}

/** Whether VS16 after `codePoint` widens it from one cell to two. */
export function widensToEmoji(codePoint: number): boolean {
  return NARROW_TO_WIDE.has(codePoint);
}
"""


def pack(entries: list[str]) -> list[str]:
    lines, line = [], "  "
    for entry in entries:
        if len(line) + len(entry) + 1 > WIDTH:
            lines.append(line.rstrip())
            line = "  "
        line += entry + " "
    lines.append(line.rstrip())
    return lines


def main() -> None:
    if version("rich") != RICH:
        raise SystemExit(f"expected Rich {RICH}, got {version('rich')}")
    table = load(UNICODE)
    if table.unicode_version != UNICODE:
        raise SystemExit(f"Rich {RICH} has no Unicode {UNICODE} table, got {table.unicode_version}")

    merged: list[list[int]] = []
    for first, last, cells in sorted(table.widths):
        if cells not in (0, 2):
            raise SystemExit(f"{first:#x}..{last:#x} has width {cells}; RANGES holds only 0 and 2")
        if merged and merged[-1][1] >= first:
            raise SystemExit(f"{first:#x} overlaps the range before it")
        if merged and merged[-1][1] + 1 == first and merged[-1][2] == cells:
            merged[-1][1] = last
        else:
            merged.append([first, last, cells])

    ranges = pack([f"[0x{a:x}, 0x{b:x}, {c}]," for a, b, c in merged])
    wide = pack([f"0x{ord(ch):x}," for ch in sorted(table.narrow_to_wide)])
    OUT.write_text(HEADER + "\n".join(ranges) + "\n" + MIDDLE + "\n".join(wide) + "\n" + FOOTER)
    print(f"{OUT}: {len(merged)} ranges, {len(table.narrow_to_wide)} VS16 code points")


if __name__ == "__main__":
    main()
