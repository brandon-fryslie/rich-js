"""Build src/renderables/html-entities.ts.

    uv run scripts/html-entities.py

The table is Python's html.entities.html5, read as markdown-it-py reads it in
markdown_it/common/entities.py: each name with its `;` stripped, so a legacy
name written with and without one is a single entry. That module is where
Rich's parser gets its entities, so this is the table Rich decodes with. It is
HTML's list of named character references, which WHATWG has frozen: the
standard says the list will not change, so the output is not expected to either.
"""

import html.entities
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/renderables/html-entities.ts"
WIDTH = 120

HEADER = """\
/**
 * HTML's named character references, each name without its `;`, to the
 * characters it stands for — the table markdown-it-py, Rich's parser, decodes
 * with. Generated by scripts/html-entities.py from Python's
 * `html.entities.html5`; regenerate rather than edit.
 */

const NAMED_REFERENCES: Readonly<Record<string, string>> = {
"""

FOOTER = """\
};

/** The characters `name`, a reference's name without its `&` and `;`, stands for, if it names any. */
export function namedReference(name: string): string | undefined {
  // An own key only: `constructor` names nothing here, whatever the prototype holds.
  return Object.hasOwn(NAMED_REFERENCES, name) ? NAMED_REFERENCES[name] : undefined;
}
"""


def literal(chars: str) -> str:
    """`chars` as a TypeScript string literal, everything outside printable ASCII escaped."""
    out = []
    for ch in chars:
        code = ord(ch)
        if ch in '"\\' or not 0x20 <= code < 0x7F:
            out.append(f"\\u{{{code:x}}}" if code > 0xFFFF else f"\\u{code:04x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main() -> None:
    table: dict[str, str] = {}
    for name, chars in html.entities.html5.items():
        key = name.rstrip(";")
        if table.setdefault(key, chars) != chars:
            raise SystemExit(f"{key} names two different strings")
    lines, line = [], "  "
    for key in sorted(table):
        entry = f"{key}: {literal(table[key])},"
        if len(line) + len(entry) + 1 > WIDTH:
            lines.append(line.rstrip())
            line = "  "
        line += entry + " "
    lines.append(line.rstrip())
    OUT.write_text(HEADER + "\n".join(lines) + "\n" + FOOTER)
    print(f"{OUT}: {len(table)} names")


if __name__ == "__main__":
    main()
